export const DICTS: Record<string, Record<string, string>> = { en, de, fr, ru };

export function tFor(locale: string): (s: string) => string {
  const d = DICTS[locale];
  if (!d) return (s) => s;
  return (s) => d[s] ?? s;
}

export function isLocale(v: string | undefined): v is Locale {
  return !!v && LOCALES.some((l) => l.code === v);
}
